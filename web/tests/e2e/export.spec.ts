import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";

const FORBIDDEN = ["sk_test_FAKE", "+91-00000-00000", "misses deadlines", "closer supervision", "Prof. Iyer"];

async function publishAs(page: import("@playwright/test").Page) {
  await page.addInitScript(() => {
    localStorage.setItem("continuum-tour-seen", "1");
    if (!localStorage.getItem("continuum-role")) localStorage.setItem("continuum-role", "lead");
  });
  await page.goto("/handovers/h_1/conflicts");
  await page.getByRole("button", { name: /Mark unresolved/ }).click();
  await page.goto("/handovers/h_1/ledger");
  await page.getByRole("button", { name: /Approve all Verified claims/ }).click();
  await page.getByRole("button", { name: /Approve all remaining/ }).click();
  await page.getByRole("button", { name: "Approve and publish" }).click();
  await expect(page.getByText(/Published v\d+ · locked/)).toBeVisible();
}

test("Contributor Markdown export: states, source links, no lead-only text", async ({ page }) => {
  await publishAs(page);
  await page.evaluate(() => localStorage.setItem("continuum-role", "contributor"));
  await page.goto("/handovers/h_1/start");
  const [download] = await Promise.all([page.waitForEvent("download"), page.getByRole("button", { name: "Export as Markdown" }).click()]);
  expect(download.suggestedFilename()).toMatch(/^continuum-handover-h_1-v\d+-contributor\.md$/);
  const md = readFileSync(await download.path(), "utf-8");
  expect(md).toContain("Generated by Continuum; every claim cites its source.");
  expect(md).toContain("Approved by: reviewer");
  expect(md).toContain("[Verified]");
  expect(md).toMatch(/\[PR #87 — [^\]]+\]\(https:\/\/github\.com\/[^)]+\/pull\/87\)/);
  for (const f of FORBIDDEN) expect(md).not.toContain(f);
});

test("Lead can export; print view contains the handover and hides the app chrome", async ({ page }) => {
  await publishAs(page);
  await page.goto("/handovers/h_1/start");
  // open the printable view without the native dialog
  await page.evaluate(() => (window.print = () => {}));
  await page.getByRole("button", { name: "Print / Save as PDF" }).click();
  await page.emulateMedia({ media: "print" });
  const portal = page.locator("#print-portal");
  await expect(portal).toBeVisible();
  await expect(portal).toContainText("Generated by Continuum; every claim cites its source.");
  await expect(portal).toContainText("[Verified]");
  await expect(page.getByRole("banner")).toBeHidden(); // site header is not printed
  for (const f of ["sk_test_FAKE", "+91-00000-00000"]) await expect(portal).not.toContainText(f);
});
