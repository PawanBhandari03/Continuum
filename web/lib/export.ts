// Export of the handover as Markdown / printable page.
// SAFETY RULE: only what GET /handovers/{id}/view returned for the viewer's role is exported
// (hidden claims are never fetched or written; only the hidden COUNT appears), and citations come
// from the role-scoped evidence endpoint. Quotes that overlap a redaction are masked.
import type { Api } from "./api";
import { chipLabel } from "./chip";
import type { AckStatus, Claim, ClaimType, EvidenceState, EvidenceUnit, Handover, Role, SectionKey } from "./types";

export interface ExportCitation {
  label: string;
  source: string;
  url: string | null;
  quote: string;
  support: "full" | "partial";
}
export interface ExportClaim {
  id: string;
  statement: string;
  state: EvidenceState;
  type: ClaimType;
  owner: string | null;
  date: string | null;
  review: Claim["review_status"];
  confirmed_by: string | null;
  confirmed_at: string | null;
  citations: ExportCitation[];
}
export interface ExportSection {
  key: SectionKey;
  title: string;
  ack: AckStatus;
  claims: ExportClaim[];
}
export interface ExportModel {
  handover: Handover;
  role: Role;
  generated_at: string;
  sections: ExportSection[];
  hidden_count: number;
}

export const GENERATED_LINE = "Generated by Continuum; every claim cites its source.";
const STATE_LABEL: Record<EvidenceState, string> = { verified: "Verified", inferred: "Inferred", conflicting: "Conflicting", missing: "Missing", confirmed: "Confirmed" };
const TYPE_LABEL: Record<ClaimType, string> = { decision: "Decision", risk: "Risk", dependency: "Dependency", owner: "Owner", next_action: "Next action", open_question: "Open question", fact: "Fact", gap: "Gap" };
const ROLE_LABEL: Record<Role, string> = { lead: "Reviewer (Lead)", contributor: "Successor (Contributor)", leaver: "Leaver" };

/** Mask any part of the quote that falls inside a redaction of its source unit. */
export function safeQuote(unit: EvidenceUnit, quote: string): string {
  if (!unit.redactions.length) return quote;
  const i = unit.text.toLowerCase().indexOf(quote.toLowerCase());
  if (i < 0) return "[quote withheld: its source contains redacted text]";
  let out = "";
  let lastMasked = false;
  for (let k = 0; k < quote.length; k++) {
    const pos = i + k;
    const masked = unit.redactions.some((r) => pos >= r.start && pos < r.end);
    if (masked) {
      if (!lastMasked) out += "[redacted]";
    } else out += quote[k];
    lastMasked = masked;
  }
  return out;
}

export async function buildExportModel(api: Pick<Api, "getView" | "getEvidence">, hid: string, role: Role): Promise<ExportModel> {
  const view = await api.getView(hid, role);
  const sections: ExportSection[] = [];
  for (const s of view.sections) {
    const claims: ExportClaim[] = [];
    for (const c of s.claims) {
      const details = await api.getEvidence(c.id, role); // throws on failure: never export a claim without its citations
      const citations: ExportCitation[] = c.citations.map((ci) => {
        const d = details.find((x) => x.citation.evidence_id === ci.evidence_id);
        if (!d) throw new Error(`Evidence ${ci.evidence_id} for claim ${c.id} is not available to this role; export stopped.`);
        return {
          label: chipLabel(d.unit),
          source: d.source.name,
          url: /^https?:\/\//.test(d.unit.locator) ? d.unit.locator : null,
          quote: safeQuote(d.unit, ci.quote),
          support: ci.support,
        };
      });
      claims.push({ id: c.id, statement: c.statement, state: c.state, type: c.type, owner: c.owner, date: c.date, review: c.review_status, confirmed_by: c.confirmed_by, confirmed_at: c.confirmed_at, citations });
    }
    sections.push({ key: s.key, title: s.title, ack: s.ack, claims });
  }
  return { handover: view.handover, role, generated_at: new Date().toISOString(), sections, hidden_count: view.hidden_count };
}

const day = (iso?: string | null) => (iso ? iso.slice(0, 10) : "");
const oneLine = (t: string) => t.replace(/\s*\n\s*/g, " ").trim();
const cap = (t: string) => t.charAt(0).toUpperCase() + t.slice(1);

export function headerLines(m: ExportModel): string[] {
  const h = m.handover;
  const lines = [
    `Version: v${h.version}`,
    `Status: ${h.status === "published" ? "Published (approved and locked)" : "DRAFT, not yet published or approved"}`,
    `Approved by: ${h.approved_by ?? "not yet approved"}`,
    `Published: ${h.published_at ? h.published_at : "not yet published"}`,
    `Target handover date: ${day(h.target_date)}`,
    `Exported for role: ${ROLE_LABEL[m.role]} · exported ${m.generated_at}`,
  ];
  return lines;
}

export function toMarkdown(m: ExportModel): string {
  const h = m.handover;
  const out: string[] = [];
  out.push(`# Handover: ${cap(h.leaver)} → ${cap(h.successor)} (CampusKart)`, "");
  headerLines(m).forEach((l) => out.push(`- ${l}`));
  out.push("", `> ${GENERATED_LINE}`, "");
  if (h.status !== "published") out.push("> **Draft.** The reviewer has not approved or published this version.", "");
  out.push("Evidence states: **Verified** (source states it and a check confirmed it) · **Inferred** (AI inference, not stated in any source) · **Conflicting** (sources disagree) · **Missing** (no evidence found) · **Confirmed** (a person confirmed it).", "");
  m.sections.forEach((s, i) => {
    out.push(`## ${i + 1}. ${s.title}`, "");
    if (s.ack !== "none") out.push(`_Successor status: ${s.ack === "acknowledged" ? "acknowledged" : "flagged unclear"}_`, "");
    if (!s.claims.length) out.push("_Nothing visible to this role in this section._", "");
    for (const c of s.claims) {
      out.push(`- **[${STATE_LABEL[c.state]}]** ${oneLine(c.statement)}`);
      const meta = [TYPE_LABEL[c.type], c.owner ? `Owner: ${cap(c.owner)}` : "", c.date ? `Date: ${c.date}` : "", c.review === "pending" ? "Not yet reviewed" : cap(c.review), c.confirmed_by ? `Confirmed by ${c.confirmed_by}${c.confirmed_at ? ` on ${day(c.confirmed_at)}` : ""}` : ""].filter(Boolean);
      out.push(`  - ${meta.join(" · ")}`);
      if (!c.citations.length) out.push("  - Sources: none (this claim has no citations)");
      else {
        out.push("  - Sources:");
        for (const ci of c.citations) {
          const q = oneLine(ci.quote);
          const sup = ci.support === "partial" ? " (partial support)" : "";
          out.push(ci.url ? `    - [${ci.label} — ${ci.source}](${ci.url}) — “${q}”${sup}` : `    - ${ci.source} (${ci.label}) — “${q}”${sup}`);
        }
      }
    }
    out.push("");
  });
  if (m.hidden_count > 0) out.push(`_${m.hidden_count} item${m.hidden_count > 1 ? "s were" : " was"} withheld by access level. Only the count is shown._`, "");
  out.push("---", GENERATED_LINE, "");
  return out.join("\n");
}

export function exportFileName(m: ExportModel, ext: string): string {
  return `continuum-handover-${m.handover.id}-v${m.handover.version}-${m.role}.${ext}`;
}

/** Browser download of text content. */
export function downloadText(name: string, text: string, mime = "text/markdown") {
  const url = URL.createObjectURL(new Blob([text], { type: `${mime};charset=utf-8` }));
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
